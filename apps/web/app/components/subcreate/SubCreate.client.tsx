import { runnerFetch } from '~/lib/runner/client';
import { useState } from 'react';
import { Link, useLocation } from '@remix-run/react';

import { liveRecipeSchema, parseDataset, type LiveRecipe as Recipe } from '~/lib/subcreate/recipe';
import { useStore } from '@nanostores/react';
import { selectedModel } from '~/lib/stores/ai';
import { ProjectHarness } from '~/components/harness/HarnessReport';

type Build = {
  project: string;
  files: string[];
  recipe_sha256: string;
  self_check: { passed: boolean; solo_score: number; scores: number[]; weights: number[] };
};
const runner = 'http://127.0.0.1:8787';

export function SubCreate() {
  const location = useLocation();
  const draft = (location.state as { draft?: unknown } | null)?.draft;
  const [recipe, setRecipe] = useState<Recipe>();
  const [source, setSource] = useState('');
  const [problem, setProblem] = useState(typeof draft === 'string' ? draft.slice(0, 2000) : '');
  const [dataset, setDataset] = useState('');
  const model = useStore(selectedModel);
  const [result, setResult] = useState<Build>();
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');
  async function generate() {
    setBusy(true);
    setError('');
    setResult(undefined);
    setRecipe(undefined);
    try {
      parseDataset(dataset);
      const response = await fetch('/api/subcreate', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ problem, model: model || undefined }),
        signal: AbortSignal.timeout(65000),
      });
      if (!response.ok) throw new Error(await response.text());
      const data = (await response.json()) as { recipe: unknown; generatedAt: string };
      setRecipe(liveRecipeSchema.parse(data.recipe));
      setSource(`Generated by configured model · ${new Date(data.generatedAt).toLocaleString()}`);
    } catch (error) {
      setError(error instanceof Error ? error.message : 'Recipe generation failed.');
    } finally {
      setBusy(false);
    }
  }
  async function build() {
    if (!recipe) return;
    setBusy(true);
    setError('');
    setResult(undefined);
    try {
      const response = await runnerFetch(`${runner}/subcreate/assemble-live`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', 'X-Bitcode-Client': 'studio' },
        body: JSON.stringify({ recipe, dataset: parseDataset(dataset) }),
        signal: AbortSignal.timeout(20000),
      });
      const body = (await response.json()) as Build & { detail?: unknown };
      if (!response.ok)
        throw new Error(
          typeof body.detail === 'string'
            ? body.detail
            : Array.isArray(body.detail)
              ? body.detail.map((item: { msg?: string }) => item.msg || 'Invalid input').join(' ')
              : 'Recipe validation failed.',
        );
      setResult(body as Build);
    } catch (error) {
      setError(error instanceof Error ? error.message : 'Assembly failed.');
    } finally {
      setBusy(false);
    }
  }
  return (
    <main className="studio-home wallet-page" style={{ maxWidth: 1000 }}>
      <p className="studio-eyebrow">SUBCREATE · BITTENSOR V11</p>
      <h1>A subnet built from blocks.</h1>
      <p>
        Describe the problem and supply labelled evaluation data. Your configured AI selects reviewed blocks; the
        generated miner uses real model inference.
      </p>
      <form
        className="flex flex-col gap-4 my-6"
        onSubmit={(event) => {
          event.preventDefault();
          void generate();
        }}
      >
        <label>
          Problem to solve
          <textarea
            required
            minLength={10}
            maxLength={2000}
            disabled={busy}
            className="block w-full border rounded p-3 mt-2"
            rows={3}
            value={problem}
            onChange={(event) => {
              setProblem(event.target.value);
              setRecipe(undefined);
              setResult(undefined);
            }}
          />
        </label>
        <label>
          Labelled evaluation data · JSONL
          <textarea
            required
            disabled={busy}
            className="block w-full border rounded p-3 mt-2 font-mono text-sm"
            rows={6}
            value={dataset}
            onChange={(event) => {
              setDataset(event.target.value);
              setResult(undefined);
            }}
          />
        </label>
        <p className="text-sm opacity-70">
          Use one JSON object per line with “input” and “answer” strings, 2–1,000 unique inputs. For classification, use
          2–32 distinct labels. Supply data you have checked; no synthetic examples are inserted. The problem goes to
          your configured AI provider; the dataset is saved only to the local runner during assembly.
        </p>
        <button disabled={busy}>Generate recipe with configured AI</button>
      </form>
      {error && (
        <p role="alert" className="my-4 p-4 border rounded">
          {error}
        </p>
      )}
      {busy && (
        <p role="status" className="my-4">
          Working…
        </p>
      )}
      {recipe && (
        <>
          <section className="studio-next">
            <p className="studio-eyebrow">{source}</p>
            <h2>{recipe.problem}</h2>
            <dl>
              {Object.entries(recipe.brief).map(([label, text]) => (
                <div className="my-4" key={label}>
                  <dt className="font-semibold">{label.replaceAll('_', ' ')}</dt>
                  <dd className="opacity-70 mt-1">{text}</dd>
                </div>
              ))}
            </dl>
          </section>
          <section className="studio-cards" aria-label="Selected building blocks">
            {[
              ['Task', recipe.task.block],
              ['Ground truth', `${recipe.ground_truth.block} · ${recipe.ground_truth.params.file}`],
              [
                'Scoring',
                recipe.scoring.map((part) => `${part.block} (${Math.round(part.weight * 100)}%)`).join(' + '),
              ],
              ['Anti-cheat', recipe.anti_cheat.join(' + ')],
              ['Weights', `${recipe.weights.block} · ${JSON.stringify(recipe.weights.params)}`],
            ].map(([name, detail]) => (
              <article className="studio-card" key={name}>
                <h2>{name}</h2>
                <p className="break-words">{detail}</p>
              </article>
            ))}
          </section>
          <p className="my-6 opacity-70">
            The generated miner requires model credentials and makes real inference requests. Assembly does not start
            nodes or create a subnet. Lexical scoring is a baseline; validate its suitability for your task.
          </p>
          <details className="my-4">
            <summary>View recipe JSON</summary>
            <pre className="overflow-auto text-xs p-4 border rounded">{JSON.stringify(recipe, null, 2)}</pre>
          </details>
          <button disabled={busy} onClick={() => void build()}>
            Assemble project and check code
          </button>
        </>
      )}
      {result && (
        <section className="studio-next">
          <h2>Project assembled · offline checks passed</h2>
          <p>
            {result.files.length} files saved to {result.project}.
          </p>
          <p>Code compilation and offline scoring checks passed. These checks do not verify inference or deployment.</p>
          <ProjectHarness key={result.project} project={result.project} />
          <Link to={`/runner?project=${encodeURIComponent(result.project)}`}>Open project in runner →</Link>
          <Link className="block mt-3" to={`/nodes?project=${encodeURIComponent(result.project)}`}>
            Launch miner in Nodes →
          </Link>
          <details className="mt-4">
            <summary>Generated files</summary>
            <ul>
              {result.files.map((file) => (
                <li key={file}>
                  <code>{file}</code>
                </li>
              ))}
            </ul>
          </details>
          <p>
            Not deployed. Configure miner inference, register and start nodes, then run the validator. The generated
            validator can submit actual localnet weights only with its explicit --submit option. No rewards have been
            measured.
          </p>
        </section>
      )}
    </main>
  );
}
